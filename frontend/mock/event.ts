// 模拟后端缓存：logo 只解析一次
const logoCache = new Map<string, string>();
function resolveLogo(domain: string): string {
  if (!logoCache.has(domain)) {
    logoCache.set(domain, `https://logo.clearbit.com/${domain}`);
  }
  return logoCache.get(domain)!;
}

