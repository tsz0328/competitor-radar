"""把 HTTP 状态码翻译成用户能看懂的中文说明。

抓取失败提示和监控源的 last_error 都直接展示这些文字，所以措辞要面向
不懂技术的运营同学——重点说清"发生了什么、通常怎么解决"，而不是抛个冷冰冰的
"HTTP 404"。
"""


# 常见状态码的专属解释；没列出来的走 4xx/5xx 兜底。
_HTTP_EXPLANATIONS: dict[int, str] = {
    400: "网页拒绝访问（400：请求格式有误）",
    401: "需要登录后才能访问（401：未授权）",
    403: "网站禁止访问该页面（403：无权限）",
    404: "页面不存在（404）：监控网址可能有误，或页面已被删除/改名，请检查链接是否正确",
    408: "请求超时（408），网站响应太慢",
    410: "页面已被永久删除（410）",
    429: "访问过于频繁被限流（429），请稍后重试",
    451: "页面因法律原因被屏蔽（451）",
    500: "网站服务器出错（500）",
    502: "网关错误（502），网站可能正在重启",
    503: "网站暂时不可用（503），可能正在维护",
    504: "网关超时（504），网站响应太慢",
}


def explain_http_status(code: int) -> str:
    """把 HTTP 状态码转成人话。

    命中专属解释就用专属的；4xx 统一说成"客户端错误"、5xx 统一说成"服务器错误"，
    避免把不明状态码直接暴露给用户。
    """
    if code in _HTTP_EXPLANATIONS:
        return _HTTP_EXPLANATIONS[code]
    if 400 <= code < 500:
        return f"网页打不开（HTTP {code}：客户端错误）"
    if 500 <= code < 600:
        return f"网页打不开（HTTP {code}：服务器错误）"
    return f"HTTP {code}"
